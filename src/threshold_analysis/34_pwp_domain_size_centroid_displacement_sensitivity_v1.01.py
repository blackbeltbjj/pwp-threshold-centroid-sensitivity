def finite(values):
    x = np.asarray(values, dtype=float)
    return x[np.isfinite(x)]


def fmean(values):
    x = finite(values)
    return float(np.mean(x)) if x.size else np.nan


def fmedian(values):
    x = finite(values)
    return float(np.median(x)) if x.size else np.nan


def fstd(values):
    x = finite(values)
    return float(np.std(x, ddof=1)) if x.size >= 2 else np.nan


def fq(values, q):
    x = finite(values)
    return float(np.quantile(x, q)) if x.size else np.nan


def unwrap_longitude_deg(lon360):
    lon = np.asarray(lon360, dtype=float)
    u = np.rad2deg(np.unwrap(np.deg2rad(lon)))
    if np.isfinite(np.nanmedian(lon)) and np.isfinite(np.nanmedian(u)):
        shift = np.round((np.nanmedian(u) - np.nanmedian(lon)) / 360.0)
        u = u - 360.0 * shift
    return u


def wrap_delta_longitude_deg(delta):
    return ((np.asarray(delta, dtype=float) + 180.0) % 360.0) - 180.0


def spherical_reference_centroid(lon_deg, lat_deg):
    lon = np.deg2rad(np.asarray(lon_deg, dtype=float))
    lat = np.deg2rad(np.asarray(lat_deg, dtype=float))
    ok = np.isfinite(lon) & np.isfinite(lat)
    lon, lat = lon[ok], lat[ok]
    x = np.cos(lat) * np.cos(lon)
    y = np.cos(lat) * np.sin(lon)
    z = np.sin(lat)
    X, Y, Z = float(np.mean(x)), float(np.mean(y)), float(np.mean(z))
    resultant = float(np.sqrt(X * X + Y * Y + Z * Z))
    lon_ref = math.degrees(math.atan2(Y, X)) % 360.0
    lat_ref = math.degrees(math.atan2(Z, math.sqrt(X * X + Y * Y)))
    return lon_ref, lat_ref, resultant


def great_circle_distance_km(lon1, lat1, lon2, lat2):
    lon1 = np.deg2rad(np.asarray(lon1, dtype=float))
    lat1 = np.deg2rad(np.asarray(lat1, dtype=float))
    lon2 = np.deg2rad(np.asarray(lon2, dtype=float))
    lat2 = np.deg2rad(np.asarray(lat2, dtype=float))
    dlon = lon2 - lon1
    dlat = lat2 - lat1
    a = np.sin(dlat / 2.0) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2.0) ** 2
    a = np.clip(a, 0.0, 1.0)
    return 2.0 * EARTH_RADIUS_KM * np.arcsin(np.sqrt(a))


