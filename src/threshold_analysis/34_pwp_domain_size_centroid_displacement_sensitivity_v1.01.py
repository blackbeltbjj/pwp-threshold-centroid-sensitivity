def strictly_decreasing(x):
    return bool(np.all(np.diff(np.asarray(x, dtype=float)) < 0.0))


def strictly_increasing(x):
    return bool(np.all(np.diff(np.asarray(x, dtype=float)) > 0.0))


def build_decision_registry(summary, pairwise):
    s = summary.sort_values("threshold_c")
    area_down = strictly_decreasing(s["mean_area_km2"])
    lon_amp_up = strictly_increasing(s["longitude_robust_amplitude_deg"])
    lon_std_up = strictly_increasing(s["longitude_std_deg"])
    radial_up = strictly_increasing(s["radial_excursion_p95_km"])
    all_sep = bool(np.all(pairwise["median_separation_km"].to_numpy(float) > 0.0))

    if area_down and lon_amp_up and radial_up:
        status = "SUPPORTED_BY_ROBUST_LONGITUDINAL_AND_RADIAL_METRICS"
        text = (
            "As the threshold-defined domain becomes smaller, both robust longitudinal amplitude "
            "and P95 radial centroid excursion increase monotonically. This supports the geometric-"
            "sensitivity hypothesis."
        )
    elif area_down and (lon_amp_up or lon_std_up or radial_up):
        status = "PARTIALLY_SUPPORTED"
        text = (
            "Domain area decreases monotonically with threshold, while only some centroid-amplitude "
            "metrics increase monotonically. Geometric sensitivity therefore depends on more than "
            "total area alone."
        )
    else:
        status = "NOT_MONOTONICALLY_SUPPORTED"
        text = (
            "The three thresholds do not show a simple monotonic inverse domain-size/centroid-amplitude "
            "ordering. Geometry, connectivity, asymmetry and the location of boundary changes must be "
            "considered."
        )

    return {
        "mean_area_strictly_decreases_28_to_29": area_down,
        "longitude_robust_amplitude_strictly_increases_28_to_29": lon_amp_up,
        "longitude_std_strictly_increases_28_to_29": lon_std_up,
        "radial_p95_strictly_increases_28_to_29": radial_up,
        "all_pairwise_median_centroid_separations_positive": all_sep,
        "geometric_sensitivity_status": status,
        "geometric_sensitivity_interpretation": text,
    }


