def load_threshold_series(threshold_c, source):
    df = pd.read_csv(source, low_memory=False)
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise KeyError(f"Missing columns in {source}: {missing}")

    df["date"] = pd.to_datetime(df["date"], errors="raise")
    if df["date"].duplicated().any():
        raise ValueError(f"Duplicate dates in {source}")

    numeric = (
        "lon_360", "lon_180", "lat", "area_km2", "pwp_cell_count",
        "valid_ocean_cell_count", "mask_cell_count", "ocean_data_coverage_pct",
        "mean_pwp_sst_c", "max_pwp_sst_c", "area_weighted_sst_std_c",
        "threshold_c", "centroid_resultant_length", "centroid_angular_dispersion_deg",
    )
    for col in numeric:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    df["threshold_fallback_used"] = parse_bool_series(df["threshold_fallback_used"])
    if not np.allclose(df["threshold_c"].dropna().to_numpy(float), threshold_c):
        raise ValueError(f"threshold_c mismatch in {source}")

    flag = df["quality_flag"].astype(str).str.upper()
    no_pwp = flag.str.contains("NO_PWP_CELLS", regex=False, na=False)
    valid = (
        np.isfinite(df["area_km2"].to_numpy(float))
        & np.isfinite(df["lon_360"].to_numpy(float))
        & np.isfinite(df["lat"].to_numpy(float))
        & np.isfinite(df["ocean_data_coverage_pct"].to_numpy(float))
        & (df["ocean_data_coverage_pct"].to_numpy(float) >= FINAL_MINIMUM_COVERAGE_PCT)
        & ~df["threshold_fallback_used"].to_numpy(bool)
        & ~no_pwp.to_numpy(bool)
    )

    rejected = int((~valid).sum())
    df = df.loc[valid].copy().sort_values("date").reset_index(drop=True)
    if df.empty:
        raise ValueError(f"No valid rows remain for {threshold_c:.1f} °C")

    df["lon_unwrapped_deg"] = unwrap_longitude_deg(df["lon_360"].to_numpy(float))
    ref_lon, ref_lat, ref_r = spherical_reference_centroid(df["lon_360"], df["lat"])
    df["reference_lon_360"] = ref_lon
    df["reference_lat"] = ref_lat
    df["reference_resultant_length"] = ref_r
    df["radial_excursion_km"] = great_circle_distance_km(df["lon_360"], df["lat"], ref_lon, ref_lat)

    df.attrs["rejected_rows"] = rejected
    df.attrs["reference_lon_360"] = ref_lon
    df.attrs["reference_lat"] = ref_lat
    df.attrs["reference_resultant_length"] = ref_r
    return df


def load_all_thresholds():
    series = {t: load_threshold_series(t, INPUT_FILES[t]) for t in THRESHOLDS_C}
    common = set(series[28.0]["date"])
    for t in THRESHOLDS_C[1:]:
        common &= set(series[t]["date"])
    common = pd.DatetimeIndex(sorted(common))
    if common.empty:
        raise ValueError("No common dates across thresholds after QC.")
    for t in THRESHOLDS_C:
        series[t] = series[t].loc[series[t]["date"].isin(common)].copy().sort_values("date").reset_index(drop=True)
        if len(series[t]) != len(common):
            raise ValueError("Common-date alignment failure.")
    return series


