def build_daily_wide(series):
    out = None
    for t in THRESHOLDS_C:
        tag = threshold_tag(t)
        df = series[t]
        cur = pd.DataFrame({
            "date": df["date"],
            f"area_km2_{tag}": df["area_km2"].to_numpy(float),
            f"lon_360_{tag}": df["lon_360"].to_numpy(float),
            f"lon_unwrapped_deg_{tag}": df["lon_unwrapped_deg"].to_numpy(float),
            f"lat_{tag}": df["lat"].to_numpy(float),
            f"radial_excursion_km_{tag}": df["radial_excursion_km"].to_numpy(float),
        })
        out = cur if out is None else out.merge(cur, on="date", how="inner", validate="one_to_one")

    for t1, t2 in ((28.0, 28.5), (28.0, 29.0), (28.5, 29.0)):
        a, b = threshold_tag(t1), threshold_tag(t2)
        pair = f"{a}_vs_{b}"
        out[f"delta_lon_deg_{pair}"] = wrap_delta_longitude_deg(out[f"lon_360_{b}"] - out[f"lon_360_{a}"])
        out[f"delta_lat_deg_{pair}"] = out[f"lat_{b}"] - out[f"lat_{a}"]
        out[f"centroid_separation_km_{pair}"] = great_circle_distance_km(out[f"lon_360_{a}"], out[f"lat_{a}"], out[f"lon_360_{b}"], out[f"lat_{b}"])
        out[f"area_ratio_{b}_to_{a}"] = out[f"area_km2_{b}"] / out[f"area_km2_{a}"]

    return out.sort_values("date").reset_index(drop=True)


