def summarize_threshold(t, df):
    area = df["area_km2"].to_numpy(float)
    lon = df["lon_unwrapped_deg"].to_numpy(float)
    lat = df["lat"].to_numpy(float)
    radial = df["radial_excursion_km"].to_numpy(float)

    area_mean = fmean(area)
    area_std = fstd(area)
    lon_p05, lon_p25, lon_p50, lon_p75, lon_p95 = [fq(lon, q) for q in (0.05, 0.25, 0.50, 0.75, 0.95)]
    lat_p05, lat_p25, lat_p50, lat_p75, lat_p95 = [fq(lat, q) for q in (0.05, 0.25, 0.50, 0.75, 0.95)]
    area_p05, area_p25, area_p50, area_p75, area_p95 = [fq(area, q) for q in (0.05, 0.25, 0.50, 0.75, 0.95)]

    return {
        "threshold_c": t,
        "n_days": len(df),
        "start_date": df["date"].min(),
        "end_date": df["date"].max(),
        "reference_lon_360": float(df["reference_lon_360"].iloc[0]),
        "reference_lat": float(df["reference_lat"].iloc[0]),
        "reference_resultant_length": float(df["reference_resultant_length"].iloc[0]),
        "mean_area_km2": area_mean,
        "mean_area_million_km2": area_mean / 1e6,
        "median_area_km2": area_p50,
        "median_area_million_km2": area_p50 / 1e6,
        "std_area_km2": area_std,
        "cv_area_pct": 100.0 * area_std / area_mean,
        "area_p05_km2": area_p05,
        "area_p95_km2": area_p95,
        "area_iqr_km2": area_p75 - area_p25,
        "area_p95_p05_km2": area_p95 - area_p05,
        "longitude_mean_deg": fmean(lon),
        "longitude_median_deg": lon_p50,
        "longitude_std_deg": fstd(lon),
        "longitude_p05_deg": lon_p05,
        "longitude_p95_deg": lon_p95,
        "longitude_iqr_deg": lon_p75 - lon_p25,
        "longitude_robust_amplitude_deg": lon_p95 - lon_p05,
        "longitude_full_range_deg": float(np.nanmax(lon) - np.nanmin(lon)),
        "latitude_mean_deg": fmean(lat),
        "latitude_median_deg": lat_p50,
        "latitude_std_deg": fstd(lat),
        "latitude_p05_deg": lat_p05,
        "latitude_p95_deg": lat_p95,
        "latitude_iqr_deg": lat_p75 - lat_p25,
        "latitude_robust_amplitude_deg": lat_p95 - lat_p05,
        "latitude_full_range_deg": float(np.nanmax(lat) - np.nanmin(lat)),
        "radial_excursion_mean_km": fmean(radial),
        "radial_excursion_median_km": fmedian(radial),
        "radial_excursion_p05_km": fq(radial, 0.05),
        "radial_excursion_p95_km": fq(radial, 0.95),
        "radial_excursion_max_km": float(np.nanmax(radial)),
    }


def build_threshold_summary(series):
    out = pd.DataFrame([summarize_threshold(t, series[t]) for t in THRESHOLDS_C]).sort_values("threshold_c").reset_index(drop=True)
    primary = out.loc[np.isclose(out["threshold_c"], PRIMARY_THRESHOLD_C)].iloc[0]
    metrics = {
        "mean_area_million_km2": "mean_area",
        "longitude_std_deg": "longitude_std",
        "longitude_robust_amplitude_deg": "longitude_robust_amplitude",
        "latitude_std_deg": "latitude_std",
        "latitude_robust_amplitude_deg": "latitude_robust_amplitude",
        "radial_excursion_p95_km": "radial_excursion_p95",
    }
    for col, name in metrics.items():
        denom = float(primary[col])
        out[f"{name}_ratio_vs_28C"] = out[col] / denom
        out[f"{name}_pct_change_vs_28C"] = 100.0 * (out[col] / denom - 1.0)
    return out


