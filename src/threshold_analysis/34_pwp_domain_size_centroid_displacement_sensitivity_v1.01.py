def build_spatial_distribution_summary(series):
    """
    Build publication-oriented statistics for the canonical daily centroid
    populations.

    The long-term mean centroid is calculated correctly on the sphere:
    daily centroid lon/lat -> 3-D unit vectors -> mean vector -> lon/lat.

    It is NOT the arithmetic mean of longitude and latitude.
    """
    rows = []

    for threshold_c in THRESHOLDS_C:
        data = series[threshold_c]

        lon_360 = data["lon_360"].to_numpy(dtype=float)
        lon_unwrapped = data["lon_unwrapped_deg"].to_numpy(dtype=float)
        lat = data["lat"].to_numpy(dtype=float)
        area = data["area_km2"].to_numpy(dtype=float)

        mean_lon, mean_lat, resultant = spherical_reference_centroid(
            lon_360,
            lat,
        )

        rows.append(
            {
                "threshold_c": threshold_c,
                "n_days": int(len(data)),
                "start_date": data["date"].min(),
                "end_date": data["date"].max(),
                "mean_spherical_lon_360_deg": mean_lon,
                "mean_spherical_lat_deg": mean_lat,
                "mean_spherical_resultant_length": resultant,
                "median_longitude_deg": fmedian(lon_unwrapped),
                "median_latitude_deg": fmedian(lat),
                "longitude_p05_deg": fq(lon_unwrapped, 0.05),
                "longitude_p95_deg": fq(lon_unwrapped, 0.95),
                "latitude_p05_deg": fq(lat, 0.05),
                "latitude_p95_deg": fq(lat, 0.95),
                "mean_daily_pwp_area_km2": fmean(area),
                "median_daily_pwp_area_km2": fmedian(area),
                "mean_daily_pwp_area_million_km2": fmean(area) / 1.0e6,
                "median_daily_pwp_area_million_km2": fmedian(area) / 1.0e6,
                "source_program": "OSAF Program 05",
                "analysis_program": "OSAF Program 34 v1.01",
                "source_file": str(INPUT_FILES[threshold_c]),
                "centroid_method": (
                    "daily area-weighted spherical centroid; "
                    "long-term mean from mean 3-D unit vector"
                ),
                "provenance_policy": (
                    "canonical frozen centroid products only; "
                    "PWP definition not recomputed"
                ),
            }
        )

    return (
        pd.DataFrame(rows)
        .sort_values("threshold_c")
        .reset_index(drop=True)
    )


