def threshold_folder_name(threshold_c: float) -> str:
    if float(threshold_c).is_integer():
        return str(int(threshold_c))
    return f"{threshold_c:g}"


def centroid_csv_path(threshold_c: float) -> Path:
    """
    Resolve the authoritative Program-05 centroid series.

    Prefer central config path resolution when available.
    """
    config = getattr(P17, "project_config", None)

    if config is not None and hasattr(config, "get_threshold_paths"):
        try:
            paths = config.get_threshold_paths(float(threshold_c))
            centroid_group = getattr(paths, "centroid", None)
            if centroid_group is not None:
                candidate = (
                    Path(centroid_group.processed_dir)
                    / "pwp_centroid_series.csv"
                )
                if candidate.is_file():
                    return candidate
        except Exception:
            pass

    folder = threshold_folder_name(threshold_c)

    candidates = (
        PROJECT_ROOT / "data" / "processed" / folder
        / "centroid" / "pwp_centroid_series.csv",

        PROJECT_ROOT / "data" / "processed" / folder
        / "pwp_centroid_series.csv",
    )

    for candidate in candidates:
        if candidate.is_file():
            return candidate

    raise FileNotFoundError(
        f"Program-05 centroid series not found for {threshold_c:.1f} °C.\n"
        + "\n".join(str(path) for path in candidates)
    )


def identify_date_column(frame: pd.DataFrame) -> str:
    """Identify the date/time column in a centroid CSV."""
    preferred = (
        "date", "Date", "DATE",
        "time", "Time", "TIME",
        "datetime", "timestamp",
    )

    for name in preferred:
        if name in frame.columns:
            return name

    # Conservative fallback: first column that parses predominantly as dates.
    for name in frame.columns:
        parsed = pd.to_datetime(frame[name], errors="coerce")
        if parsed.notna().mean() >= 0.95:
            return name

    raise ValueError(
        "No date/time column could be identified in centroid series."
    )


def load_common_dates() -> pd.DatetimeIndex:
    """
    Load the intersection of authoritative Program-05 dates for all thresholds.
    """
    date_sets: list[set[pd.Timestamp]] = []

    print("## AUTHORITATIVE PROGRAM-05 DATE SERIES")
    print()

    for threshold in THRESHOLDS_C:
        path = centroid_csv_path(threshold)
        frame = pd.read_csv(path)
        date_column = identify_date_column(frame)

        dates = pd.DatetimeIndex(
            pd.to_datetime(frame[date_column], errors="coerce")
        ).normalize()
        dates = dates[~dates.isna()]

        unique_dates = set(pd.Timestamp(value) for value in dates.unique())
        date_sets.append(unique_dates)

        print(
            f"{threshold:4.1f} °C : {len(unique_dates):,} dates | {path}"
        )

    common = sorted(set.intersection(*date_sets))

    if not common:
        raise ValueError(
            "No common dates were found among the three centroid series."
        )

    common_dates = pd.DatetimeIndex(common)

    print()
    print(
        f"Common daily record : {len(common_dates):,} dates | "
        f"{common_dates.min():%Y-%m-%d} to {common_dates.max():%Y-%m-%d}"
    )
    print()

    return common_dates


