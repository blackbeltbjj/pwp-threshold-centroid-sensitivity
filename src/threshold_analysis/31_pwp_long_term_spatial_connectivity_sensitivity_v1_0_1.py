DAILY_COLUMNS = [
    field.name
    for field in DailyConnectivityDiagnostic.__dataclass_fields__.values()
]


def load_checkpoint() -> pd.DataFrame:
    if not CHECKPOINT_CSV.is_file():
        return pd.DataFrame(columns=DAILY_COLUMNS)

    frame = pd.read_csv(CHECKPOINT_CSV)

    required = set(DAILY_COLUMNS)
    missing = required.difference(frame.columns)

    if missing:
        raise ValueError(
            "Checkpoint exists but is incompatible with Program 31 v1.0.1.\n"
            f"Missing columns: {sorted(missing)}\n"
            f"Checkpoint: {CHECKPOINT_CSV}"
        )

    frame["date"] = pd.to_datetime(frame["date"]).dt.strftime("%Y-%m-%d")

    print(
        f"Checkpoint loaded : {len(frame):,} completed date × threshold rows"
    )

    return frame[DAILY_COLUMNS].copy()


def completed_keys(frame: pd.DataFrame) -> set[tuple[str, float]]:
    if frame.empty:
        return set()

    return set(
        zip(
            frame["date"].astype(str),
            frame["threshold_c"].astype(float),
        )
    )


def write_checkpoint(records: list[dict]) -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)

    frame = pd.DataFrame(records, columns=DAILY_COLUMNS)

    if frame.empty:
        return

    frame = (
        frame
        .drop_duplicates(subset=["date", "threshold_c"], keep="last")
        .sort_values(["date", "threshold_c"])
        .reset_index(drop=True)
    )

    frame.to_csv(
        CHECKPOINT_CSV,
        index=False,
        float_format="%.8f",
    )


