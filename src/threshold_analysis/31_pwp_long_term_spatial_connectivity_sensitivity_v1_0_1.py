def signed_longitude_difference_deg(a_deg: float, b_deg: float) -> float:
    """Signed shortest angular difference a - b in [-180, 180)."""
    return float((a_deg - b_deg + 180.0) % 360.0 - 180.0)


def great_circle_distance_km(
    lon1_deg: float,
    lat1_deg: float,
    lon2_deg: float,
    lat2_deg: float,
) -> float:
    """Great-circle distance between two geographic positions."""
    radius_km = float(getattr(P17, "EARTH_RADIUS_KM", 6371.0088))

    lon1 = np.deg2rad(lon1_deg)
    lat1 = np.deg2rad(lat1_deg)
    lon2 = np.deg2rad(lon2_deg)
    lat2 = np.deg2rad(lat2_deg)

    dlon = lon2 - lon1
    dlat = lat2 - lat1

    a = (
        np.sin(dlat / 2.0) ** 2
        + np.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2.0) ** 2
    )

    angle = 2.0 * np.arcsin(np.sqrt(np.clip(a, 0.0, 1.0)))
    return float(radius_km * angle)


