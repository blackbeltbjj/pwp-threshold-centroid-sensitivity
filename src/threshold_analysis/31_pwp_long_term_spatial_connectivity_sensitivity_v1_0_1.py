"""
===============================================================================
OSAF PROGRAM 31 — LONG-TERM PWP SPATIAL-CONNECTIVITY SENSITIVITY
===============================================================================

VERSION
    1.0.1

PURPOSE
    Quantify, over the complete daily observational record, how the SST
    threshold used to define the Pacific Warm Pool (PWP) affects its spatial
    connectivity and the robustness of its spherical centroid.

    Program 31 is the long-term extension of the connected-component diagnostic
    introduced in Program 30 v1.2.0.

SCIENTIFIC QUESTION
    Does the centroid calculated from ALL threshold-qualified PWP cells remain
    representative of the dominant connected warm-pool body through time?

    The analysis is performed independently for:

        28.0 °C
        28.5 °C
        29.0 °C

    For every available daily SST field, Program 31 compares:

        A) FULL THRESHOLD DOMAIN
           all valid Pacific-mask cells satisfying SST >= threshold;

        B) LARGEST CONNECTED COMPONENT
           the spatially connected threshold-defined component having the
           greatest spherical area.

PRIMARY DIAGNOSTICS
    For every date × threshold:

        - number of connected components;
        - total PWP area;
        - largest connected-component area;
        - fraction of total area in the largest component;
        - full-domain spherical centroid;
        - largest-component spherical centroid;
        - signed longitude difference;
        - latitude difference;
        - great-circle centroid separation.

CONNECTIVITY CONVENTION
    Eight-neighbour connectivity is used.

    Therefore, horizontal, vertical, and diagonal cell contacts are considered
    connected.

    Components are ranked by SPHERICAL AREA, not by grid-cell count.

IMPORTANT INTERPRETATION
    The number of components alone is NOT used as the principal coherence
    metric. Numerous very small isolated components can coexist with a highly
    coherent principal PWP.

    The primary coherence metric is:

        largest_component_area_fraction
            = largest_component_area / total_PWP_area

    The primary centroid-sensitivity metric is:

        centroid_distance_km
            = great-circle distance between the full-domain centroid and the
              centroid of the largest connected component.

AUTHORITATIVE UPSTREAM METHODOLOGY
    Program 31 does NOT redefine:

        - the Pacific Ocean mask;
        - the SST grid;
        - spherical grid-cell area;
        - spherical centroid mathematics;
        - SST-unit conversion;
        - longitude normalization;
        - daily OISST extraction.

    These operations are imported from:

        src_a/17_methodological_domain_figure.py

    Program 17 itself uses the fixed validated Pacific mask generated by the
    upstream mask workflow, including:

        src_a/01_build_mask.py
        src_a/02_test_mask.py
        src_a/04_interpolate_mask.py

AUTHORITATIVE CENTROID SERIES
    Program 05 calculates the project's threshold-specific PWP centroid series.

    Program 31 uses the Program-05 centroid CSVs to define the authoritative
    dates available for each threshold and to cross-check the full-domain
    centroid calculation.

    Expected locations:

        data/processed/28/centroid/pwp_centroid_series.csv
        data/processed/28.5/centroid/pwp_centroid_series.csv
        data/processed/29/centroid/pwp_centroid_series.csv

    with fallback support for:

        data/processed/<threshold>/pwp_centroid_series.csv

    IMPORTANT:
        Program 31 does NOT overwrite Program-05 centroid products.

INPUT DATA
    1. Daily NOAA OISST absolute SST NetCDF files beneath:

           data/raw/

       The exact file discovery, SST-variable identification, coordinate
       handling, SST-unit conversion, Pacific-mask alignment, and daily field
       loading are delegated to Program 17.

    2. Fixed Pacific mask and reference grids used by Program 17.

    3. Program-05 threshold-specific centroid series.

TEMPORAL DOMAIN
    Complete common daily record available simultaneously for:

        - Program-05 centroid dates at 28.0 °C;
        - Program-05 centroid dates at 28.5 °C;
        - Program-05 centroid dates at 29.0 °C.

    No temporal interpolation or climate-index upsampling is performed.

OUTPUT TABLES
    outputs/tables/threshold_comparison/pwp_long_term_connectivity/

        pwp_daily_connectivity_diagnostics.csv
            Long-format daily diagnostic table.

        pwp_connectivity_threshold_summary.csv
            Full-record threshold comparison.

        pwp_connectivity_annual_summary.csv
            Annual threshold-specific statistics.

        pwp_connectivity_extreme_days.csv
            Most spatially fragmented / centroid-sensitive days.

OUTPUT FIGURES
    outputs/figures/threshold_comparison/pwp_long_term_connectivity/

        pwp_largest_component_fraction_timeseries.png/pdf
        pwp_centroid_separation_timeseries.png/pdf
        pwp_connectivity_threshold_distributions.png/pdf
        pwp_connectivity_threshold_summary.png/pdf

CHECKPOINT / RESUME
    Because the analysis spans the complete daily record and requires daily
    spatial SST fields, Program 31 writes a checkpoint periodically:

        outputs/tables/threshold_comparison/pwp_long_term_connectivity/
            pwp_daily_connectivity_checkpoint.csv

    If interrupted, rerunning the program resumes from completed
    date × threshold combinations.

    The checkpoint is removed only after successful creation of the final daily
    table.

DEPENDENCIES
    Python 3.10+
    numpy
    pandas
    scipy
    matplotlib

    plus the dependencies already required by Program 17 (including xarray for
    OISST NetCDF access).

VERSION 1.0.1 CORRECTION
    Program 17's calculate_threshold_diagnostic() attaches event metadata and is
    valid only for its two representative dates. Program 31 v1.0.1 therefore
    uses Program 17's lower-level pwp_domain(), spherical_centroid(), and
    spherical_cell_areas_km2() methods directly for the complete daily record.

SCIENTIFIC ROLE IN THE PROJECT
    Program 31 is intended as the FINAL threshold-selection diagnostic before
    scientific freeze of the manuscript methodology.

    It is designed to determine whether 28.0 °C or 28.5 °C provides the most
    defensible primary PWP definition over the complete record, while evaluating
    29.0 °C as a warm-core sensitivity threshold.

    The program must not choose the threshold automatically. It produces the
    evidence required for the scientific decision.

===============================================================================
"""

