def process_full_record(common_dates: pd.DatetimeIndex) -> pd.DataFrame:
    """
    Process the complete daily record.

    NOTE
    ----
    Daily spatial SST fields are deliberately loaded through Program 17 so that
    Program 31 uses exactly the same grid alignment, fixed Pacific mask, SST
    conversion, and longitude convention as the validated methodological
    workflow.

    A checkpoint makes this long-running operation restartable.
    """
    checkpoint = load_checkpoint()

    records = (
        checkpoint.to_dict("records")
        if not checkpoint.empty
        else []
    )

    done = completed_keys(checkpoint)

    total_expected = len(common_dates) * len(THRESHOLDS_C)

    print()
    print("## PROCESSING COMPLETE DAILY RECORD")
    print()
    print(f"Expected diagnostics : {total_expected:,}")
    print(f"Already completed    : {len(done):,}")
    print()

    processed_dates_since_checkpoint = 0

    for index, date in enumerate(common_dates, start=1):
        date_string = f"{date:%Y-%m-%d}"

        missing_thresholds = [
            threshold
            for threshold in THRESHOLDS_C
            if (date_string, float(threshold)) not in done
        ]

        if not missing_thresholds:
            continue

        try:
            field = P17.load_daily_field(date)
            cell_areas = P17.spherical_cell_areas_km2(
                field.latitude,
                field.longitude,
            )

            for threshold in missing_thresholds:
                diagnostic = calculate_one(
                    field=field,
                    threshold_c=threshold,
                    cell_areas_km2=cell_areas,
                )

                record = asdict(diagnostic)
                records.append(record)
                done.add((date_string, float(threshold)))

            processed_dates_since_checkpoint += 1

            if (
                processed_dates_since_checkpoint >= CHECKPOINT_EVERY_DATES
                or index == len(common_dates)
            ):
                write_checkpoint(records)
                processed_dates_since_checkpoint = 0

            if index == 1 or index % 100 == 0 or index == len(common_dates):
                print(
                    f"{index:6,d}/{len(common_dates):,} | "
                    f"{date_string} | "
                    f"{len(done):,}/{total_expected:,} diagnostics"
                )

        except KeyboardInterrupt:
            write_checkpoint(records)
            print()
            print("Interrupted by user. Checkpoint saved.")
            raise

        except Exception:
            write_checkpoint(records)
            print()
            print(
                f"ERROR on {date_string}. Checkpoint saved before stopping."
            )
            raise

    final = pd.DataFrame(records, columns=DAILY_COLUMNS)

    final = (
        final
        .drop_duplicates(subset=["date", "threshold_c"], keep="last")
        .sort_values(["date", "threshold_c"])
        .reset_index(drop=True)
    )

    if len(final) != total_expected:
        raise RuntimeError(
            "Final daily table is incomplete.\n"
            f"Expected: {total_expected:,}\n"
            f"Found   : {len(final):,}"
        )

    TABLE_DIR.mkdir(parents=True, exist_ok=True)

    final.to_csv(
        DAILY_CSV,
        index=False,
        float_format="%.8f",
    )

    if CHECKPOINT_CSV.is_file():
        CHECKPOINT_CSV.unlink()

    return final


