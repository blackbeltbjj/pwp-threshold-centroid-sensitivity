def figure_distributions(daily: pd.DataFrame) -> tuple[Path, Path]:
    fig, axes = plt.subplots(
        2,
        1,
        figsize=(10, 9),
        constrained_layout=True,
    )

    bins_fraction = np.linspace(0.0, 1.0, 51)

    max_distance = float(
        daily["centroid_distance_km"].quantile(0.995)
    )
    max_distance = max(max_distance, 1000.0)
    bins_distance = np.linspace(0.0, max_distance, 60)

    for threshold in THRESHOLDS_C:
        group = daily[daily["threshold_c"] == threshold]

        axes[0].hist(
            group["largest_component_area_fraction"],
            bins=bins_fraction,
            histtype="step",
            density=True,
            linewidth=1.4,
            label=f"{threshold:.1f} °C",
        )

        clipped = group["centroid_distance_km"].clip(
            upper=max_distance
        )

        axes[1].hist(
            clipped,
            bins=bins_distance,
            histtype="step",
            density=True,
            linewidth=1.4,
            label=f"{threshold:.1f} °C",
        )

    axes[0].set_xlabel("Largest-component fraction of total PWP area")
    axes[0].set_ylabel("Density")
    axes[0].grid(alpha=0.20)
    axes[0].legend(frameon=False)

    axes[1].set_xlabel("Full vs largest-component centroid separation (km)")
    axes[1].set_ylabel("Density")
    axes[1].grid(alpha=0.20)
    axes[1].legend(frameon=False)

    fig.suptitle(
        "Threshold sensitivity of PWP spatial connectivity",
        fontsize=14,
    )

    return save_figure(
        fig,
        "pwp_connectivity_threshold_distributions",
    )


