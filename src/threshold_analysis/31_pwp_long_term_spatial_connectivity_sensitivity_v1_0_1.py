def pct(series: pd.Series, q: float) -> float:
    return float(series.quantile(q))


def build_threshold_summary(daily: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict] = []

    for threshold, group in daily.groupby("threshold_c", sort=True):
        fraction = group["largest_component_area_fraction"].astype(float)
        distance = group["centroid_distance_km"].astype(float)

        row = {
            "threshold_c": float(threshold),
            "n_days": int(len(group)),
            "start_date": str(group["date"].min()),
            "end_date": str(group["date"].max()),

            "component_count_median":
                float(group["component_count"].median()),

            "largest_fraction_mean": float(fraction.mean()),
            "largest_fraction_median": float(fraction.median()),
            "largest_fraction_p05": pct(fraction, 0.05),
            "largest_fraction_p25": pct(fraction, 0.25),
            "largest_fraction_p75": pct(fraction, 0.75),
            "largest_fraction_p95": pct(fraction, 0.95),

            "centroid_distance_km_mean": float(distance.mean()),
            "centroid_distance_km_median": float(distance.median()),
            "centroid_distance_km_p75": pct(distance, 0.75),
            "centroid_distance_km_p95": pct(distance, 0.95),
            "centroid_distance_km_p99": pct(distance, 0.99),
            "centroid_distance_km_max": float(distance.max()),
        }

        for level in AREA_FRACTION_LEVELS:
            key = f"pct_days_largest_fraction_lt_{int(level * 100):02d}"
            row[key] = float(100.0 * (fraction < level).mean())

        for level in CENTROID_DISTANCE_LEVELS_KM:
            key = f"pct_days_centroid_distance_gt_{int(level):04d}_km"
            row[key] = float(100.0 * (distance > level).mean())

        rows.append(row)

    summary = pd.DataFrame(rows)

    summary.to_csv(
        THRESHOLD_SUMMARY_CSV,
        index=False,
        float_format="%.8f",
    )

    return summary


def build_annual_summary(daily: pd.DataFrame) -> pd.DataFrame:
    frame = daily.copy()
    frame["date"] = pd.to_datetime(frame["date"])
    frame["year"] = frame["date"].dt.year

    rows: list[dict] = []

    for (year, threshold), group in frame.groupby(
        ["year", "threshold_c"],
        sort=True,
    ):
        fraction = group["largest_component_area_fraction"].astype(float)
        distance = group["centroid_distance_km"].astype(float)

        rows.append(
            {
                "year": int(year),
                "threshold_c": float(threshold),
                "n_days": int(len(group)),
                "largest_fraction_mean": float(fraction.mean()),
                "largest_fraction_median": float(fraction.median()),
                "largest_fraction_p05": pct(fraction, 0.05),
                "centroid_distance_km_mean": float(distance.mean()),
                "centroid_distance_km_median": float(distance.median()),
                "centroid_distance_km_p95": pct(distance, 0.95),
                "pct_days_largest_fraction_lt_90":
                    float(100.0 * (fraction < 0.90).mean()),
                "pct_days_centroid_distance_gt_500_km":
                    float(100.0 * (distance > 500.0).mean()),
                "pct_days_centroid_distance_gt_1000_km":
                    float(100.0 * (distance > 1000.0).mean()),
            }
        )

    annual = pd.DataFrame(rows)

    annual.to_csv(
        ANNUAL_SUMMARY_CSV,
        index=False,
        float_format="%.8f",
    )

    return annual


def build_extreme_days(daily: pd.DataFrame) -> pd.DataFrame:
    """
    Save the most informative fragmented / centroid-sensitive days.

    For each threshold:
        - 25 lowest largest-component fractions;
        - 25 greatest centroid separations.
    """
    selected: list[pd.DataFrame] = []

    for threshold, group in daily.groupby("threshold_c", sort=True):
        low_fraction = group.nsmallest(
            25,
            "largest_component_area_fraction",
        ).copy()
        low_fraction["selection_reason"] = "lowest_largest_component_fraction"

        high_distance = group.nlargest(
            25,
            "centroid_distance_km",
        ).copy()
        high_distance["selection_reason"] = "greatest_centroid_separation"

        selected.extend([low_fraction, high_distance])

    extremes = pd.concat(selected, ignore_index=True)

    extremes = (
        extremes
        .drop_duplicates(
            subset=["date", "threshold_c", "selection_reason"]
        )
        .sort_values(
            ["threshold_c", "selection_reason", "date"]
        )
        .reset_index(drop=True)
    )

    extremes.to_csv(
        EXTREME_DAYS_CSV,
        index=False,
        float_format="%.8f",
    )

    return extremes


