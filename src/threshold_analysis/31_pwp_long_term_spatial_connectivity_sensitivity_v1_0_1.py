def largest_component_by_spherical_area(
    domain: np.ndarray,
    cell_areas_km2: np.ndarray,
) -> tuple[np.ndarray, int, float]:
    """
    Identify the connected component having the greatest spherical area.
    """
    if domain.shape != cell_areas_km2.shape:
        raise ValueError(
            "PWP domain and cell-area grid have inconsistent shapes."
        )

    labels, component_count = ndimage.label(
        domain.astype(bool),
        structure=CONNECTIVITY_STRUCTURE,
    )

    component_count = int(component_count)

    if component_count < 1:
        raise ValueError("No connected PWP component was identified.")

    ids = np.arange(1, component_count + 1, dtype=int)

    areas = np.asarray(
        ndimage.sum(
            input=cell_areas_km2,
            labels=labels,
            index=ids,
        ),
        dtype=np.float64,
    )

    largest_index = int(np.argmax(areas))
    largest_label = int(ids[largest_index])

    return (
        labels == largest_label,
        component_count,
        float(areas[largest_index]),
    )


def calculate_one(
    field,
    threshold_c: float,
    cell_areas_km2: np.ndarray,
) -> DailyConnectivityDiagnostic:
    """
    Calculate connectivity and centroid sensitivity for one day/threshold.

    Program 17's calculate_threshold_diagnostic() is deliberately NOT used
    here because that wrapper is restricted to Program 17's two representative
    dates through REPRESENTATIVE_DATES.

    Program 31 instead uses Program 17's validated low-level methods directly:
        - pwp_domain()
        - spherical_centroid()
        - spherical_cell_areas_km2()
    """

    full_domain = P17.pwp_domain(
        field,
        threshold_c,
    )

    if not np.any(full_domain):
        raise ValueError(
            f"No PWP cells on {field.date:%Y-%m-%d} "
            f"at {threshold_c:.1f} °C."
        )

    total_area_km2 = float(
        np.sum(
            cell_areas_km2[full_domain],
            dtype=np.float64,
        )
    )

    if not np.isfinite(total_area_km2) or total_area_km2 <= 0.0:
        raise ValueError(
            f"Invalid PWP area on {field.date:%Y-%m-%d} "
            f"at {threshold_c:.1f} °C: {total_area_km2}"
        )

    full_lon, full_lat = P17.spherical_centroid(
        latitude=field.latitude,
        longitude=field.longitude,
        weights=cell_areas_km2,
        selected=full_domain,
    )

    largest_domain, component_count, largest_area_km2 = (
        largest_component_by_spherical_area(
            domain=full_domain,
            cell_areas_km2=cell_areas_km2,
        )
    )

    largest_lon, largest_lat = P17.spherical_centroid(
        latitude=field.latitude,
        longitude=field.longitude,
        weights=cell_areas_km2,
        selected=largest_domain,
    )

    full_lon = float(full_lon)
    full_lat = float(full_lat)
    largest_lon = float(largest_lon)
    largest_lat = float(largest_lat)

    fraction = float(largest_area_km2 / total_area_km2)

    if fraction > 1.0 + 1.0e-10:
        raise ValueError(
            "Largest component area exceeds total PWP area on "
            f"{field.date:%Y-%m-%d} at {threshold_c:.1f} °C."
        )

    fraction = float(np.clip(fraction, 0.0, 1.0))

    delta_lon = signed_longitude_difference_deg(
        full_lon,
        largest_lon,
    )
    delta_lat = float(full_lat - largest_lat)

    distance = great_circle_distance_km(
        full_lon,
        full_lat,
        largest_lon,
        largest_lat,
    )

    return DailyConnectivityDiagnostic(
        date=f"{field.date:%Y-%m-%d}",
        year=int(field.date.year),
        threshold_c=float(threshold_c),
        connectivity=CONNECTIVITY_LABEL,
        component_count=component_count,
        total_area_km2=total_area_km2,
        largest_component_area_km2=float(largest_area_km2),
        largest_component_area_fraction=fraction,
        full_centroid_lon_360=full_lon,
        full_centroid_lat=full_lat,
        largest_centroid_lon_360=largest_lon,
        largest_centroid_lat=largest_lat,
        delta_lon_deg=delta_lon,
        delta_lat_deg=delta_lat,
        centroid_distance_km=distance,
    )


